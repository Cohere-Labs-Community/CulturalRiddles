"""Prepare and run the riddle-difficulty decomposition.

The decomposition separates how often a model answers correctly into model,
riddle, language, community, topic, and model-by-community components with
crossed random-effects logistic models. Model fitting runs in R (``lme4``)
because it fits crossed random effects on ~100k rows in minutes; this module
owns the sample definition and the model-free checks.

Run from the repository root::

    uv run python -m analysis.difficulty_decomposition.prepare
    uv run python -m analysis.difficulty_decomposition.prepare --fit
"""

from __future__ import annotations

import argparse
import subprocess
from pathlib import Path

import numpy as np
import pandas as pd

from analysis.constants import BUILD_DIR, COMMONCRAWL_STATS_CSV, DIFFICULTY_OUTPUT_DIR
from analysis.corpus import load_corpus_metadata
from analysis.difficulty_decomposition.fit_provenance import (
    record_fit_provenance,
    validate_fit_provenance,
)
from analysis.model_names import load_model_name_mapping
from analysis.model_results.evaluation_data import load_flat_frame
from analysis.utils import write_csv

PACKAGE_DIR = Path(__file__).resolve().parent
OUTPUT_DIR = DIFFICULTY_OUTPUT_DIR
# Row-level frame of every model answer, regenerated by ``main``.
FRAME_PATH = BUILD_DIR / "difficulty" / "frame.csv"
R_SCRIPT = PACKAGE_DIR / "fit_lme4.R"
COMMONCRAWL_PATH = COMMONCRAWL_STATS_CSV

# A community x model block counts as fully graded when at most this share of
# its answers is unresolved (pending or with an invalidated grade); unresolved
# answers are the non-exact-match ones, so dropping them from partially graded
# blocks would inflate accuracy.
COMPLETE_BLOCK_MAX_PENDING = 0.02
# Topics written by every community; the remaining per-community wildcard
# topics are nested in one community and pooled into one level.
CORE_TOPIC_MIN_RIDDLES = 500
# Grader screen: human-graded answers almost always credited while model ranks
# disagree with the benchmark-wide ranking signals rubric leniency, not ease.
GRADER_MAX_HUMAN_CORRECT = 0.9
GRADER_MIN_RANK_RHO = 0.7
FRONTIER_MODELS = (
    "GPT5.5-none",
    "claude-opus-4-7",
    "deepseek-v4-pro",
    "gemini-3.1-pro-preview",
)
SMALL_MODELS = (
    "Qwen-3.5-0.8B",
    "tiny-aya-earth",
    "tiny-aya-fire",
    "tiny-aya-water",
    "tiny-aya-global",
)
MIN_SHARED_MODELS = 5


def load_frame(with_judges: bool = True) -> pd.DataFrame:
    """Load every model answer with community, model, and web-resource metadata.

    Args:
        with_judges: Count answers on which both LLM judges agree, as in the
            paper's accuracy; ``False`` keeps those answers pending.

    Returns:
        One row per model answer with ``correct`` (score 3), block completeness,
        the pooled topic, and log10 Common Crawl pages for the language.
    """
    results = load_flat_frame(with_judges=with_judges)[
        [
            "community",
            "topic",
            "riddle_id",
            "model_name",
            "score",
            "scoring_method",
            "error_type",
            "is_pending",
            "is_scored",
        ]
    ]
    # Invalidated human grades are as unresolved as pending ones: a block whose
    # graded answers were all invalidated keeps only its exact matches.
    results["pending"] = results.pop("is_pending") | results["scoring_method"].eq(
        "invalid_human_eval"
    )
    riddles_per_topic = results.drop_duplicates("riddle_id").groupby("topic").size()
    core_topics = riddles_per_topic.index[riddles_per_topic >= CORE_TOPIC_MIN_RIDDLES]
    results["topic_core"] = results["topic"].where(results["topic"].isin(core_topics), "Wildcard")
    block_pending = results.groupby(["community", "model_name"])["pending"].transform("mean")
    results["complete_block"] = block_pending <= COMPLETE_BLOCK_MAX_PENDING
    results["correct"] = results["score"].eq(3).astype(float).where(results["is_scored"])

    web = pd.read_csv(COMMONCRAWL_PATH, usecols=["language_code", "common_crawl_pages"])
    models = load_model_name_mapping()[["source_name", "display_name", "total_parameter_b"]]
    frame = (
        results.merge(load_corpus_metadata(), on="community", how="left", validate="m:1")
        .merge(web, on="language_code", how="left", validate="m:1")
        .merge(
            models,
            left_on="model_name",
            right_on="source_name",
            how="left",
            validate="m:1",
        )
        .drop(columns="source_name")
    )
    if frame["display_name"].isna().any() or frame["language_code"].isna().any():
        raise ValueError("Results contain models or communities missing from metadata")
    # A community without human evaluation can still have a block resolved by
    # judges alone; one judge-scored model cannot anchor a community's difficulty.
    frame["complete_block"] &= frame["is_human_evaluated"].astype(bool)
    # Languages with no detected pages sit below the smallest detected volume.
    frame["log10_pages"] = np.log10(frame["common_crawl_pages"].clip(lower=1_000))
    return frame


def grader_screen(frame: pd.DataFrame) -> pd.DataFrame:
    """Flag communities whose human grading looks too lenient to compare.

    Args:
        frame: Output of :func:`load_frame`.

    Returns:
        One row per community with accuracy, frontier-small gap, rank agreement
        with the benchmark-wide model order, and the ``grader_flag`` decision.
    """
    scored = frame[frame["is_scored"]]
    global_accuracy = scored.groupby("model_name")["correct"].mean()
    rows = []
    for community, group in scored.groupby("community"):
        accuracy = group.groupby("model_name")["correct"].mean()
        human = group[group["scoring_method"].eq("human_eval")]
        rows.append(
            {
                "community": community,
                "accuracy_scored": group["correct"].mean(),
                "frontier_accuracy": accuracy.reindex(FRONTIER_MODELS).mean(),
                "small_accuracy": accuracy.reindex(SMALL_MODELS).mean(),
                "rank_rho_vs_global": accuracy.corr(
                    global_accuracy.reindex(accuracy.index), method="spearman"
                ),
                "human_graded_correct_rate": human["score"].eq(3).mean() if len(human) else np.nan,
                "pending_share": frame.loc[frame["community"].eq(community), "pending"].mean(),
            }
        )
    screen = pd.DataFrame(rows)
    screen["grader_flag"] = screen["human_graded_correct_rate"].gt(
        GRADER_MAX_HUMAN_CORRECT
    ) & screen["rank_rho_vs_global"].lt(GRADER_MIN_RANK_RHO)
    return screen


def natural_experiments(sample: pd.DataFrame) -> pd.DataFrame:
    """Compare communities that share a language or a country on the same models.

    Args:
        sample: Scored responses from unflagged, human-evaluated communities.

    Returns:
        One row per community in each shared-language or shared-country group,
        with its mean model accuracy over scored responses in every group member.
    """
    accuracy = sample.groupby(["community", "model_name"])["correct"].mean().unstack()
    communities = sample.drop_duplicates("community").set_index("community")
    rows = []
    for key, label in (
        ("language_code", "same_language"),
        ("country_code", "same_country"),
    ):
        for group, members in communities.groupby(key).groups.items():
            shared = accuracy.loc[list(members)].dropna(axis=1)
            if len(members) < 2 or shared.shape[1] < MIN_SHARED_MODELS:
                continue
            means = shared.mean(axis=1)
            rows.extend(
                {
                    "comparison": label,
                    "group": group,
                    "community": community,
                    "shared_models": shared.shape[1],
                    "accuracy": means[community],
                    "group_range": means.max() - means.min(),
                    "language_code": communities.at[community, "language_code"],
                    "language_resourcedness": communities.at[community, "language_resourcedness"],
                    "un_m49_subregion": communities.at[community, "un_m49_subregion"],
                }
                for community in members
            )
    return pd.DataFrame(rows)


def main(fit: bool = False) -> None:
    """Write the analysis frame and checks, then fit or validate cached models.

    Args:
        fit: Run the R model fits after preparing the data (about 1--2 hours).

    Raises:
        subprocess.CalledProcessError: If the R fitting script fails.
        RuntimeError: If replayed fit summaries have missing or stale provenance.
    """
    frame = load_frame()
    screen = grader_screen(frame)
    flagged = set(screen.loc[screen["grader_flag"], "community"])
    frame["grader_flag"] = frame["community"].isin(flagged)
    write_csv(frame, FRAME_PATH)
    write_csv(screen.round(3), OUTPUT_DIR / "grader_screen.csv")

    sample = frame[frame["is_human_evaluated"] & frame["is_scored"] & ~frame["grader_flag"]]
    write_csv(natural_experiments(sample).round(3), OUTPUT_DIR / "natural_experiments.csv")
    if fit:
        subprocess.run(["Rscript", str(R_SCRIPT), str(FRAME_PATH), str(OUTPUT_DIR)], check=True)
        record_fit_provenance(
            "prepare", frame_path=FRAME_PATH, script_path=R_SCRIPT, output_dir=OUTPUT_DIR
        )
    else:
        validate_fit_provenance(
            "prepare", frame_path=FRAME_PATH, script_path=R_SCRIPT, output_dir=OUTPUT_DIR
        )


if __name__ == "__main__":
    parser = argparse.ArgumentParser(
        description="Prepare the difficulty sample and optionally fit the R models."
    )
    parser.add_argument("--fit", action="store_true", help="Also run the R model fits.")
    main(fit=parser.parse_args().fit)

def latex_escape(value: object) -> str:
    """Escape a cell value for a LaTeX table."""
    replacements = {
        "\\": r"\textbackslash{}",
        "&": r"\&",
        "%": r"\%",
        "$": r"\$",
        "#": r"\#",
        "_": r"\_",
        "{": r"\{",
        "}": r"\}",
    }
    return "".join(replacements.get(character, character) for character in str(value))


def format_count(value: int) -> str:
    """Format an integer for prose and commands."""
    return f"{value:,}"


def format_percent(value: float) -> str:
    """Format a percentage with two decimal places."""
    return f"{value:.2f}"


def format_stat(value: float | None, scale: float = 1.0, spec: str = ".2f") -> str:
    """Format a possibly missing statistic; missing values print as a dash."""
    return "--" if value is None else format(value * scale, spec)


def float_table(
    columns: str,
    header: str,
    rows: list[str],
    caption: str,
    label: str,
    tabcolsep: str,
) -> str:
    """Wrap rows in a full-width, small-print table float.

    Args:
        columns: LaTeX column specification.
        header: Header row without the trailing ``\\``.
        rows: Body rows, each ending in ``\\``.
        caption: Caption text.
        label: LaTeX label.
        tabcolsep: Value of ``\tabcolsep``, such as ``2pt``.

    Returns:
        The table float as LaTeX source.
    """
    return "\n".join(
        [
            r"\begin{table*}[!htbp]",
            r"  \centering",
            r"  \footnotesize",
            rf"  \setlength{{\tabcolsep}}{{{tabcolsep}}}",
            rf"  \begin{{tabular}}{{{columns}}}",
            r"    \toprule",
            f"    {header} \\\\",
            r"    \midrule",
            *(f"    {row}" for row in rows),
            r"    \bottomrule",
            r"  \end{tabular}",
            rf"  \caption{{{caption}}}",
            rf"  \label{{{label}}}",
            r"\end{table*}",
            "",
        ]
    )


def write_table(name: str, contents: str) -> Path:
    """Write one generated table to ``data/derived/tables/<name>.tex``.

    Args:
        name: Table stem, which is also the generating module's name.
        contents: LaTeX source without the generated-file header.

    Returns:
        The written path.
    """
    path = TABLES_DIR / f"{name}.tex"
    path.parent.mkdir(parents=True, exist_ok=True)
    header = f"% Generated by analysis.tables.{name}; do not edit by hand.\n"
    path.write_text(header + contents, encoding="utf-8")
    print(f"Wrote {path}")
    return path
